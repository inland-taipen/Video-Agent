// src/legacy/components/tabs/HistoryTab.tsx — the viewer's own past conversations.
import React, { useEffect, useState } from 'react';
import { api, ConversationSummary, Persona, Turn } from '../../api';
import { ErrorNote, Spinner } from '../common';

export function HistoryTab({ persona }: { persona: Persona }) {
  const [items, setItems] = useState<ConversationSummary[] | null>(null);
  const [openId, setOpenId] = useState<string | null>(null);
  const [turns, setTurns] = useState<Turn[] | null>(null);
  const [error, setError] = useState('');
  const first = persona.name.split(' ')[0];

  useEffect(() => { api.conversations(persona.id).then(setItems).catch((e) => setError(e.message)); }, [persona.id]);
  useEffect(() => {
    if (!openId) return;
    setTurns(null);
    api.conversation(openId).then((c) => setTurns(c.turns)).catch((e) => setError(e.message));
  }, [openId]);

  return (
    <div className="lg-two">
      <div>
        <ErrorNote message={error} />
        {!items && <Spinner />}
        {items?.length === 0 && <div className="lg-empty"><p>No conversations yet.</p></div>}
        <ul className="lg-list">
          {items?.map((c) => (
            <li key={c.id}>
              <button className={`lg-card lg-convo ${openId === c.id ? 'is-active' : ''}`} onClick={() => setOpenId(c.id)}>
                <strong>{new Date(c.started_at).toLocaleString()}</strong>
                <span className="lg-small lg-muted">{c.first_question ? `“${c.first_question}”` : 'No questions asked'} · {c.turns} turns</span>
              </button>
            </li>
          ))}
        </ul>
        <p className="lg-small lg-muted">Only you can see your conversations.</p>
      </div>
      <div>
        {openId && !turns && <Spinner />}
        {turns && (
          <div className="lg-card lg-history">
            <p className="lg-small lg-muted">Transcript — replies were generated by AI, not spoken by {first}.</p>
            {turns.map((t) => (
              <div key={t.id} className={`lg-hturn lg-hturn--${t.role}`}>
                <span className="lg-turn__who">{t.role === 'user' ? 'You' : `${first} (AI)`}</span>
                <p>{t.text}</p>
                {t.role === 'persona' && t.provider !== 'system' && (
                  <span className="lg-small lg-muted">{t.grounded ? `Based on ${t.source_ids.length} recorded ${t.source_ids.length === 1 ? 'memory' : 'memories'}` : 'No matching recorded memory'}</span>
                )}
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}
